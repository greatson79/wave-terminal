const assert = require('node:assert/strict');
const { splitAck, measure, expectedClose } = require('./attach-repro.cjs');
const { Terminal } = require('@xterm/headless');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { spawn } = require('node:child_process');
(async () => {
  assert.equal(splitAck(Buffer.from('{"ok":true}')), null);
  assert.deepEqual(splitAck(Buffer.from('{"ok":true}\n\x1b[Hraw')), Buffer.from('\x1b[Hraw'));
  assert.throws(() => splitAck(Buffer.from('{"ok":false}\n')), /attach rejected/);
  assert.throws(() => splitAck(Buffer.from('bad\n')), /JSON/);
  assert.equal(expectedClose(false,undefined),false);
  assert.equal(expectedClose(true,undefined),true);
  assert.equal(expectedClose(false,{complete:true,sha256:'wrong'}),false);
  assert.equal(expectedClose(false,{complete:true,sha256:'a6770aba1c94852f31f354c183a183a3c681fcd60f312ad26cc15f771949794d'}),true);
  const term = new Terminal({cols:120,rows:35,scrollback:5000,allowProposedApi:true});
  const write = data => new Promise(resolve => term.write(data, resolve));
  await write(Buffer.from(Array.from({length:100},(_,i)=>`SCROLL-${String(i+1).padStart(3,'0')}\r\n`).join('')));
  const before = measure(term);
  term.resize(70,35);
  await write(Buffer.from('\x1b[H\x1b[Jre-attach viewport\r\n'));
  const after = measure(term);
  assert.equal(before.normal.labelCount,100);
  assert.ok(after.normal.labelCount >= 65, 'screen redraw must not be mistaken for a fresh terminal reset');
  await write(Buffer.from('\x1b[3J'));
  assert.ok(measure(term).normal.labelCount < after.normal.labelCount, 'known destructive negative control');
  term.dispose();
  const wrapped = new Terminal({cols:6,rows:4,scrollback:10,allowProposedApi:true});
  await new Promise(resolve=>wrapped.write('SCROLL-001\r\n',resolve));
  assert.deepEqual(measure(wrapped).normal.labels,[1]);
  await new Promise(resolve=>wrapped.write('SCROLL-002junk\r\nSCROLL-003 suffix\r\n',resolve));
  assert.deepEqual(measure(wrapped).normal.labels,[1]);
  wrapped.dispose();
  const directory=fs.mkdtempSync(path.join(os.tmpdir(),'wave-child-selftest-'));
  const fixture=path.join(directory,'fixture.bin');
  const payload=Buffer.from('child gate and byte proof\r\n');
  fs.writeFileSync(fixture,payload);
  fs.writeFileSync(path.join(directory,'start'),'go');
  const child=spawn(process.execPath,[path.join(__dirname,'attach-repro.cjs'),'--child',fixture,directory],{stdio:['ignore','pipe','pipe']});
  const chunks=[];
  child.stdout.on('data',chunk=>chunks.push(chunk));
  const status=await new Promise((resolve,reject)=>{child.on('error',reject);child.on('exit',resolve);});
  assert.equal(status,0);
  assert.deepEqual(Buffer.concat(chunks),payload);
  assert.equal(JSON.parse(fs.readFileSync(path.join(directory,'complete.json'),'utf8')).complete,true);
  const blockedDir=path.join(directory,'must-not-exist');
  const blocked=spawn(process.execPath,[path.join(__dirname,'attach-repro.cjs'),'/not/a/real/waved',blockedDir],{env:{...process.env,GITHUB_ACTIONS:'false'},stdio:['ignore','pipe','pipe']});
  let blockedError='';
  blocked.stderr.on('data',chunk=>{blockedError+=chunk;});
  const blockedStatus=await new Promise((resolve,reject)=>{blocked.on('error',reject);blocked.on('close',resolve);});
  assert.equal(blockedStatus,1);
  assert.match(blockedError,/CI-only/);
  assert.equal(fs.existsSync(blockedDir),false);
  console.log('PASS split ACK/raw bytes, rejected ACK, same-terminal snapshot, narrow/wrapped resize, clear negative control, exact child gate/output/completion');
})().catch(error => { console.error(error); process.exitCode=1; });
